#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Стандарт публичной карточки объекта: что обязано быть на витрине и что делать, если пусто.

Эльнур 08.10.2026 (решение №271): «как минимум эталон стандарт заполнения карточек
на сайте, там до сих пор всё вразнобой». Стандарт уже записан: canon_rules №91
(«ОБЯЗАТЕЛЬНЫЙ МИНИМУМ — ПРОЕКТ / ЮНИТ»), формула «карточка объекта», агент plp-cards.
Машинная проверка полей живёт в базе — функция catalog_audit(). Здесь правил
НЕ дублируем: только сводим её ответ к минимуму канона и печатаем по каждой
продажной карточке на сайте, каких обязательных полей нет и откуда их брать.

    python3 tools/card_standard.py            # по каждой карточке
    python3 tools/card_standard.py --short    # итог для сборки (node build/all.mjs)
    python3 tools/card_standard.py --strict   # код выхода 1, если есть карточки ниже минимума

Сборку не валит: зовётся из all.mjs отдельным шагом и печатает отчёт.
Пустое поле = задача запросить у источника, а не повод выдумать (канон №91).
"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalog_audit import rows  # тот же вход в базу, что у приёмки

# Обязательный минимум канона №91 → строка catalog_audit() → откуда брать (иерархия истины канона).
ПРАЙС = 'Price List в Telegram-канале застройщика (только Available)'
СТАНДАРТ = [
    ('стадия',            ('стадия не заполнена', 'стадия не из канона'), 'сайт застройщика или папка «05 стройка»; слово из словаря стадий'),
    ('срок сдачи',        ('нет срока сдачи', 'сдан, но нет даты сдачи', 'сдача уже прошла, а стадия «строится»'), 'папка «05 стройка», договор, сайт застройщика'),
    ('цена от, бат',      ('нет цены',), ПРАЙС + '; нет прайса — на витрине «цену подтверждаем у застройщика»'),
    ('площадь',           ('нет площади',), 'папка «02 планировки»'),
    ('спальни',           ('нет спален',), 'папка «02 планировки», прайс'),
    ('описание по сути',  ('нет описания',), 'папка «04 брошюра» на Диске; по сути, не слоган'),
    ('застройщик',        ('нет застройщика',), 'папка «04 брошюра», сайт застройщика'),
    ('форма собственности', ('нет формы собственности',), 'папка «06 юридическое»: фрихолд или лизхолд'),
    ('главное фото',      ('нет снимков',), 'папка «01 фото» → tools/photos.py'),
    ('координаты',        ('нет точки на карте',), 'адрес из брошюры → точка на карте'),
    ('типы юнитов',       ('нет типов юнитов',), 'папка «02 планировки»'),
    ('цена по типам',     ('нет разбивки цен по спальням',), ПРАЙС),
]
# Минимум канона, который catalog_audit() пока не проверяет (честно печатаем, а не молчим):
НЕ_ПРОВЕРЯЕТСЯ = ['район из списка', 'наличие по типу юнита', 'планировка по типу юнита']
АРЕНДА_УПРАВЛЕНИЕ = ('аренда:', 'управление:')


def main():
    short = '--short' in sys.argv
    strict = '--strict' in sys.argv
    try:
        r = rows()
    except Exception as e:
        print('[стандарт карточки] база не ответила (%s)' % str(e)[:60])
        return 0
    по_вопросу = {}
    for поле, вопросы, _ in СТАНДАРТ:
        for в in вопросы:
            по_вопросу[в] = поле
    карточки = {}
    for x in r:
        if x['issue'].startswith(АРЕНДА_УПРАВЛЕНИЕ):
            continue   # у аренды и управления свой минимум (там же, в каноне №91), его печатает приёмка
        поле = по_вопросу.get(x['issue'])
        if not поле:
            continue
        к = карточки.setdefault(x['plp_property_id'], {'имя': x['name'] or '', 'нет': []})
        if поле not in к['нет']:
            к['нет'].append(поле)
    поля_по_счёту = {}
    for к in карточки.values():
        for п in к['нет']:
            поля_по_счёту[п] = поля_по_счёту.get(п, 0) + 1
    if short:
        print('[стандарт карточки] ниже минимума канона №91: %d карточек на сайте; чаще всего нет: %s'
              % (len(карточки), ', '.join('%s %d' % (п, n) for п, n in sorted(поля_по_счёту.items(), key=lambda t: -t[1])[:5]) or '—'))
        print('[стандарт карточки] подробно и откуда брать: python3 tools/card_standard.py')
    else:
        print('СТАНДАРТ ПУБЛИЧНОЙ КАРТОЧКИ (canon_rules №91, продажа). Обязательно:')
        for поле, _, откуда in СТАНДАРТ:
            print('  • %-20s ← %s' % (поле, откуда))
        print('  (машиной пока не проверяется: %s)' % ', '.join(НЕ_ПРОВЕРЯЕТСЯ))
        print('Если пусто: запросить у источника выше; поле заполняет plp-cards по формуле «карточка объекта», только с источником.\n')
        for код, к in sorted(карточки.items(), key=lambda t: (-len(t[1]['нет']), t[0])):
            print('%-28s %-34s нет: %s' % (код, к['имя'][:34], ', '.join(к['нет'])))
        print('\nниже минимума: %d карточек' % len(карточки))
    return 1 if (strict and карточки) else 0


if __name__ == '__main__':
    sys.exit(main())
