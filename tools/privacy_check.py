#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проверка конфиденциальности перед выкладкой сайта.

Эльнур, правило повторено не раз: «конфиденциальную инфу мы не выносим наружу,
каждому юниту достаточно дать свой айди». 23.09.2026 нашлись два файла, где лежали
настоящие номера юнитов и даже имя владельца рядом с номером: admin.html и
add-property.html. Маскировка в базе была, а в собранных страницах — нет.

Инструмент маскировки существовал и в сборку включён не был: его запускали руками
один раз, и каждая новая сборка могла засветить заново. Этот сторож закрывает дыру
с другой стороны — смотрит уже собранные страницы и кричит, если нашёл.

Что считается нарушением:
  • внутренний код юнита: PLP-ПРОЕКТ-A24, -S14, -M1 (публичные маски -U1, -R1 можно);
  • имя клиента рядом с объектом.

    python3 tools/privacy_check.py          # отчёт
    python3 tools/privacy_check.py --strict # ненулевой код выхода при находке
"""
import glob, os, re, sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# публичные маски — это U (unit) и R (rent) с цифрой; всё прочее считаем номером юнита
ВНУТРЕННИЙ = re.compile(r'PLP-[A-Z0-9]+-(?![UR]\d)[A-Z]?\d{1,4}\b')

находки = []
for путь in glob.glob(os.path.join(КОРЕНЬ, '*.html')) + glob.glob(os.path.join(КОРЕНЬ, '*', '*.html')):
    отн = os.path.relpath(путь, КОРЕНЬ)
    if отн.startswith('build/'):
        continue
    текст = open(путь, encoding='utf-8', errors='ignore').read()
    for m in set(ВНУТРЕННИЙ.findall(текст)):
        находки.append((отн, m))

if находки:
    print('[конфиденциальность] 🔴 НА САЙТЕ НАСТОЯЩИЕ НОМЕРА ЮНИТОВ: %d' % len(находки))
    for отн, код in sorted(находки)[:20]:
        print('   %s — %s' % (отн, код))
    print('   Подставьте публичный код из objects.public_code и пересоберите.')
    sys.exit(1 if '--strict' in sys.argv else 0)

print('[конфиденциальность] ок: внутренних номеров юнитов на страницах нет')
