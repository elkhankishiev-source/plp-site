#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Правка 314: двойник и есть Эльнур, ссылку просит вежливо, обещает только своё.

Эльнур 18.09.2026 поправил вчерашнюю правку 313, дословно:

  «"Ответ один: это Эльнур обсуждает сам" — он не может так ответить, это будет
   странно, он и есть Эльнур, просто уходит от темы, или съезжает, я сам отвечу
   на неё позже»

  «Материалы просит ссылкой, а не PDF — всё верно, но если отправили пдф, тоже ок,
   но ссылка это наша важная база, с которой потом ты работаешь! Не говоришь: нет,
   скиньте мне ссылку! Отправили — спасибо, а могли бы вы, пожалуйста, обновить
   вашу ссылку на гугл диск с полной инф о проекте и ценами актуальными. Заруби это!»

  «"задай деловой вопрос про условия сотрудничества" — нет необходимости,
   достаточно просто поддержать разговор»

  «всё, что он обещал, я понимаю, он не может, но тогда ему и не надо обещать,
   скажи, что передам Клод Коду, когда он войдёт в чат, как-то так, а не эту чушь»

Три ошибки вчерашней правки, которые это лечит:
  • я велел отвечать «это Эльнур обсуждает сам» — но двойник ГОВОРИТ от имени Эльнура,
    так что фраза звучит как разговор о себе в третьем лице;
  • я велел просить ссылку вместо PDF — вышло «не надо PDF», то есть отказ от того,
    что человек уже прислал. Нужно наоборот: спасибо за файл И просьба обновить ссылку;
  • деловой вопрос я заменил на «два уточняющих» — а их и вовсе не требуется.
"""
import datetime, shutil, subprocess, sys

SRC = '/opt/plp-api/brain.mjs'
APPLY = '--apply' in sys.argv

OLD_MONEY = (' спросили прямо. Ответ один: «это Эльнур обсуждает сам, передам ему». '
             'А вот спецусловия и акции"')
NEW_MONEY = (' спросили прямо. И НЕ ссылайся на Эльнура в третьем лице: ты и есть Эльнур, '
             'фраза «это Эльнур обсуждает сам» звучит как разговор о себе со стороны. '
             'Вместо этого мягко уходишь от темы и оставляешь её себе: «давай это обсудим отдельно», '
             '«к цифрам вернусь сам, чуть позже», «я тебе отдельно отвечу по этому». '
             'Дальше переводишь разговор на предмет: наличие, площади, сроки. '
             'А вот спецусловия и акции"')

OLD_PDF = ('    " МАТЕРИАЛЫ ПРОСИ ССЫЛКОЙ. Нужны свежие данные — проси ссылку на папку (Google Drive, Dropbox)"+\n'
           '    " или на страницу проекта. НЕ проси прислать PDF, файл, презентацию или прайс вложением:"+\n'
           '    " ссылка обновляется сама, файл устаревает в день получения. Прислали файл — поблагодари"+\n'
           '    " и попроси ссылку на папку, чтобы дальше брать оттуда.')
NEW_PDF = ('    " МАТЕРИАЛЫ: ФАЙЛ ПРИНИМАЕМ, ССЫЛКУ ПРОСИМ. Прислали PDF, прайс или презентацию —"+\n'
           '    " это нормально и полезно: поблагодари и скажи, что забрал. Отказывать нельзя,"+\n'
           '    " фразы «не надо файл», «скиньте лучше ссылку» запрещены."+\n'
           '    " И в ТОЙ ЖЕ реплике вежливо попроси ссылку на папку, потому что с ней мы работаем дальше:"+\n'
           '    " «спасибо, забрал. А могли бы вы, пожалуйста, обновить вашу ссылку на Google Диск"+\n'
           '    " с полной информацией по проекту и актуальными ценами, чтобы я дальше брал оттуда?»"+\n'
           '    " Если ссылку уже давали — не проси заново, скажи спасибо и уточни, обновлялась ли папка.')

OLD_Q = ('    " ОБЪЁМ: одно-два коротких предложения. Максимум ДВА уточняющих вопроса за весь разговор,"+\n'
         '    " и только по делу: наличие, площади, сроки, свежий прайс. Задал — дальше не расспрашивай:"+')
NEW_Q = ('    " ОБЪЁМ: одно-два коротких предложения. Деловой вопрос задавать НЕ ОБЯЗАТЕЛЬНО:"+\n'
         '    " достаточно просто поддержать разговор по-человечески. Если вопрос всё же нужен —"+\n'
         '    " максимум два за весь разговор и только по делу: наличие, площади, сроки, свежий прайс."+\n'
         '    " Задал — дальше не расспрашивай:"+')

# 4. Обещания: вместо выдумки — честная передача Клод Коду.
OLD_PROM = 'вместо «пришлю» говори «передам Эльнуру, он пришлёт» (или «уточню у Эльнура»)'
NEW_PROM = ('вместо «пришлю» говори «передам Клод Коду, он поднимет, когда войдёт в чат» — '
            'так и есть, задача ставится ему и он это умеет. Ссылаться на Эльнура в третьем лице '
            'нельзя: ты и есть Эльнур. И НИКОГДА не говори «зафиксировал», «взял в железо», '
            '«записал», «напомню», «подниму», если в этом же ответе не появилась настоящая запись '
            'или задача: вместо этого скажи, что передаёшь Клод Коду')


def main():
    src = open(SRC, encoding='utf-8').read()
    if 'правка 315' in src:
        print('правка 315 уже стоит')
        return 0
    steps = [(OLD_MONEY, NEW_MONEY, 'деньги: уходит от темы, не ссылается на себя со стороны'),
             (OLD_PDF, NEW_PDF, 'файл принимаем, ссылку просим вежливо'),
             (OLD_Q, NEW_Q, 'деловой вопрос не обязателен'),
             (OLD_PROM, NEW_PROM, 'обещания передаются Клод Коду')]
    miss = [w for o, _, w in steps if o not in src]
    if miss:
        print('НЕ НАЙДЕНО: %s — правка отменена' % '; '.join(miss))
        return 1
    if not APPLY:
        for _, _, w in steps:
            print('будет изменено: %s' % w)
        print('\nЭто отчёт. Применить: --apply')
        return 0
    bak = SRC + '.bak_' + datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
    shutil.copy2(SRC, bak)
    for old, new, w in steps:
        src = src.replace(old, new, 1)
        print('  ✓ %s' % w)
    src = src.replace('/* 18.09.2026 правка 313.', '/* 18.09.2026 правка 313, уточнена правкой 315.', 1)
    open(SRC, 'w', encoding='utf-8').write(src)
    chk = subprocess.run(['node', '--check', SRC], capture_output=True, text=True)
    if chk.returncode:
        shutil.copy2(bak, SRC)
        print('СИНТАКСИС СЛОМАН — откатил:\n' + chk.stderr[:400])
        return 1
    print('синтаксис ок; копия: %s' % bak)
    subprocess.run(['systemctl', 'restart', 'plp-api'], capture_output=True, timeout=120)
    subprocess.run(['sleep', '4'])
    st = subprocess.run(['systemctl', 'is-active', 'plp-api'], capture_output=True, text=True).stdout.strip()
    print('сервис: %s' % st)
    if st != 'active':
        shutil.copy2(bak, SRC)
        subprocess.run(['systemctl', 'restart', 'plp-api'], capture_output=True, timeout=120)
        print('не поднялся — откатил')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
