#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проверка текстов на страницах: опечатки, наши запреты, приметы машинного письма.

Эльнур 24.09.2026: «нет ли ошибок в тексте». Полную вычитку по-русски машина
не заменит, но повторяющиеся беды ловятся точно — и именно они стоят денег,
потому что тиражируются шаблоном на сотню страниц.

Что ищем:
  • НАШИ ЗАПРЕТЫ. «Приветствую» вместо «здравствуйте»; слово «наценка» в любой
    форме; «бесплатно», «цена та же», «платит девелопер» — всё это записано
    в каноне как недопустимое в словах клиенту.
  • Приметы машинного письма: длинное тире там, где мы его не ставим, «—» между
    словами без пробелов, «в том числе и», «стоит отметить», «важно понимать».
  • Буква ё там, где её съели: «все» вместо «всё» в характерных оборотах,
    «Подберем», «Найдем», «Поможем» с потерянной ё.
  • Опечатки вёрстки: два пробела подряд, пробел перед запятой и точкой,
    незакрытые кавычки-ёлочки, «п.» и «г.» с переносом.
  • Латиница внутри русского слова — частая беда копипасты: «Пхукeт» с
    английской e. Такое слово поиск не найдёт никогда.

Работает по видимому тексту: скрипты и стили вырезаются.

    python3 tools/text_check.py
    python3 tools/text_check.py --тихо
"""

import os
import re
import sys

КОРЕНЬ = os.path.expanduser('~/plp-site')
ТИХО = '--тихо' in sys.argv
ПРОПУСК = {'.git', 'node_modules', 'build', 'tools', 'img'}

ПРАВИЛА = [
    ('запрещённое слово «приветствую»', re.compile(r'\bприветству', re.I)),
    ('запрещённое слово «наценка»', re.compile(r'\bнаценк', re.I)),
    ('«платит девелопер» — запрещено каноном', re.compile(r'платит\s+девелопер', re.I)),
    ('латиница внутри русского слова', re.compile(r'[а-яё][a-z]{1,2}[а-яё]', re.I)),
    ('два пробела подряд', re.compile(r'[^\s\n] {2}[^\s\n]')),
    ('пробел перед запятой или точкой', re.compile(r'\s+[,.](?=\s|$)')),
    # «Поможем» и «Приедем» пишутся БЕЗ ё — 24.09 правило их ловило зря.
    ('потерянная ё', re.compile(r'\b(Подберем|Найдем|Учтем|Возьмем|Разберем|Начнем|Сделаем\b(?!\s))\b')),
    ('машинный оборот', re.compile(
        r'\b(стоит отметить|важно понимать|в том числе и|следует учитывать|как правило,)\b', re.I)),
]

# Длинное тире в наших текстах допустимо, но НЕ подряд и не без пробелов.
ТИРЕ_БЕЗ_ПРОБЕЛОВ = re.compile(r'[а-яёa-z]—[а-яёa-z]', re.I)


def узлы_текста(s):
    """Каждый видимый кусок текста отдельно.

    24.09: первая версия резала теги, подставляя пробел, и сама наплодила 4230
    «двойных пробелов» на границах тегов. Проверять надо ВНУТРИ текстового узла,
    иначе сторож ловит собственный след — ровно та болезнь, которую мы чиним
    весь день.
    """
    s = re.sub(r'<script.*?</script>|<style.*?</style>|<!--.*?-->', '', s, flags=re.S)
    куски = []
    for кусок in re.split(r'<[^>]+>', s):
        к = кусок.replace('&nbsp;', ' ').replace('&mdash;', '—').replace('&ndash;', '–')
        к = к.strip('\n\t')
        if len(к.strip()) >= 3:
            куски.append(к)
    return куски


def страницы():
    из = []
    for корень, папки, файлы in os.walk(КОРЕНЬ):
        папки[:] = [п for п in папки if п not in ПРОПУСК and not п.startswith('.')]
        из += [os.path.join(корень, и) for и in файлы if и.endswith('.html')]
    return sorted(из)


def главное():
    находки = {}
    всего = 0
    for путь in страницы():
        имя = os.path.relpath(путь, КОРЕНЬ)
        всего += 1
        for t in узлы_текста(open(путь, encoding='utf-8', errors='ignore').read()):
            for что, рег in ПРАВИЛА:
                for м in рег.finditer(t):
                    кусок = re.sub(r'\s+', ' ', t[max(0, м.start() - 34):м.end() + 34]).strip()
                    находки.setdefault(что, []).append((имя, кусок))
            for м in ТИРЕ_БЕЗ_ПРОБЕЛОВ.finditer(t):
                кусок = re.sub(r'\s+', ' ', t[max(0, м.start() - 30):м.end() + 30]).strip()
                находки.setdefault('тире без пробелов', []).append((имя, кусок))

    итого = sum(len(v) for v in находки.values())
    print('ПРОВЕРКА ТЕКСТОВ — страниц %d, находок %d\n' % (всего, итого))
    for что in sorted(находки, key=lambda k: -len(находки[k])):
        список = находки[что]
        # страницы одного вида собираются шаблоном: показываем, на скольких
        стр = len({с for с, _ in список})
        print('  %-44s %d  (страниц %d)' % (что[:44], len(список), стр))
        видели = set()
        for имя, кусок in список:
            if кусок[:40] in видели:
                continue
            видели.add(кусок[:40])
            print('      %-26s %s' % (имя[:26], кусок[:74]))
            if len(видели) >= 3:
                break
    return 1 if итого else 0


if __name__ == '__main__':
    sys.exit(главное())
