# -*- coding: utf-8 -*-
"""Ищет картинки, которых нет: разметка зовёт файл, а файла в репозитории нет.

Повод. 24.09.2026, Эльнур: «в разделе запросить каталог исчезала картинка».
Проверка показала: `img/catalog-mock.webp` и `img/catalog-mock-700.webp`
отдавали 404 на живом сайте. Удалил их коммит 8972458 «сжатие картинок на месте»
— сжималка не справилась с этими двумя и снесла оригиналы, а разметка осталась
ссылаться на прежние имена. Сборка прошла молча, приёмка ничего не заметила,
и блок «Получить каталог» стоял с дырой неизвестно сколько дней.

Класс ошибки простой и повторяемый: ссылка пережила файл. Ловится за секунду,
если вообще проверять, — поэтому проверяем на каждой сборке.

    python3 tools/images_check.py          # отчёт, код возврата 1 при находках
    python3 tools/images_check.py --тихо   # только при находках
"""

import os
import re
import sys

КОРЕНЬ = os.path.expanduser('~/plp-site')
ТИХО = '--тихо' in sys.argv

# Где искать ссылки. Каталоги сборки и выгрузок не трогаем.
ПРОПУСК = {'.git', 'node_modules', 'build', '_archive', 'tools'}

# src="…" и srcset="… 700w, … 1400w"
СЫЛКА = re.compile(r'(?:src|srcset|href)\s*=\s*"([^"]+)"', re.I)
КАРТИНКА = re.compile(r'\.(webp|png|jpe?g|svg|gif|avif)(\?|$)', re.I)


def адреса_из(значение):
    """srcset — это список «адрес 700w», берём из него именно адреса."""
    for кусок in значение.split(','):
        кусок = кусок.strip()
        if not кусок:
            continue
        yield кусок.split()[0]


def проверить():
    дыры = []
    всего = 0
    for корень, папки, файлы in os.walk(КОРЕНЬ):
        папки[:] = [п for п in папки if п not in ПРОПУСК and not п.startswith('.')]
        for имя in файлы:
            if not имя.endswith('.html'):
                continue
            путь = os.path.join(корень, имя)
            текст = open(путь, encoding='utf-8', errors='ignore').read()
            for значение in СЫЛКА.findall(текст):
                for адрес in адреса_из(значение):
                    if not КАРТИНКА.search(адрес):
                        continue
                    if адрес.startswith(('http://', 'https://', 'data:', '//')):
                        continue
                    if "'" in адрес or '+' in адрес or '${' in адрес:
                        continue      # адрес собирается кодом, файл узнаем только в браузере
                    всего += 1
                    чистый = адрес.split('?')[0].split('#')[0]
                    рядом = os.path.normpath(os.path.join(os.path.dirname(путь), чистый))
                    от_корня = os.path.normpath(os.path.join(КОРЕНЬ, чистый.lstrip('/')))
                    if not (os.path.exists(рядом) or os.path.exists(от_корня)):
                        дыры.append((os.path.relpath(путь, КОРЕНЬ), чистый))
    return всего, дыры


def главное():
    всего, дыры = проверить()
    if дыры:
        print('[картинки] 🔴 разметка зовёт файлы, которых нет:')
        видели = set()
        for страница, адрес in дыры:
            if (страница, адрес) in видели:
                continue
            видели.add((страница, адрес))
            print('   %-34s ← %s' % (адрес, страница))
        print('[картинки] всего ссылок %d, битых %d' % (всего, len(видели)))
        return 1
    if not ТИХО:
        print('[картинки] ок: проверено %d ссылок, все файлы на месте' % всего)
    return 0


if __name__ == '__main__':
    sys.exit(главное())
