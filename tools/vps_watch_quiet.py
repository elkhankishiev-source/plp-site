def main():
    src = open(SRC, encoding='utf-8').read()
    if 'без_чисел' in src:
        print('правка уже стоит')
        return 0
    miss = [w for o, _, w in STEPS if src.count(o) != 1]
    if miss:
        print('НЕ НАЙДЕНО однозначно: %s — отменяю' % '; '.join(miss))
        return 1
    if not APPLY:
        for _, _, w in STEPS:
            print('будет изменено: %s' % w)
        print('\nЭто отчёт. Применить: --apply')
        return 0
    bak = SRC + '.bak_' + datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
    shutil.copy2(SRC, bak)
    for old, new, w in STEPS:
        src = src.replace(old, new, 1)
        print('  ✓ %s' % w)
    open(SRC, 'w', encoding='utf-8').write(src)
    chk = subprocess.run(['python3', '-c',
                          'import ast;ast.parse(open("%s",encoding="utf-8").read())' % SRC],
                         capture_output=True, text=True)
    if chk.returncode:
        shutil.copy2(bak, SRC)
        print('СИНТАКСИС СЛОМАН — откатил:\n' + chk.stderr[:400])
        return 1
    run = subprocess.run(['python3', SRC], capture_output=True, text=True, timeout=240)
    print('\nпрогон без отправки:')
    print((run.stdout or run.stderr).strip()[-900:])
    return 0


if __name__ == '__main__':
    sys.exit(main())
