#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сторож единого вида: общие части страниц обязаны совпадать байт в байт.

Повод. 24.09.2026, Эльнур: «а разве это всё едино? не понимаю».
И до этого: «почему страница главная в другом стиле подвал?»

Как было устроено. Разметка шапки, меню и подвала лежит в build/parts и
вставляется в страницы по маркерам — это работало. А СТИЛИ каждая страница
носила свою копию, и копии тихо расходились: на add-property.html подвал остался
светлой плитой и без правил для логотипа, потому что её стили — снимок главной
неизвестной давности. Увидеть это можно было только глазами, и Эльнур увидел.

Что проверяем:
  1. Кусок PLP:UI на каждой странице обязан совпадать с build/parts/ui-common.css.
     Это общие стили, у них один источник.
  2. Кусок PLP:FOOTER обязан быть одинаковым на всех страницах: подвал у нас
     один, вариантов у него нет.
  3. Шапка и мобильное меню сверяются между страницами одного вида: у сайта и
     кабинета они отличаются намеренно (переключатель «Сайт / Кабинет»),
     поэтому сравниваем внутри своей группы, а не все со всеми.

Молчит, пока всё сходится. Возвращает 1, если что-то разъехалось.

    python3 tools/parts_check.py
    python3 tools/parts_check.py --тихо
"""

import os
import re
import sys

КОРЕНЬ = os.path.expanduser('~/plp-site')
ТИХО = '--тихо' in sys.argv


def ровно(кусок_текста):
    """Убираем законные различия: страницы в подпапках ссылаются через ../,
    и от глубины разметка отличается, хотя часть та же. 24.09: первая версия
    сторожа этого не учла и объявила разошедшимися 10 страниц из 31 — сторож,
    который врёт, хуже, чем никакого."""
    # Адреса ссылок отличаются ЗАКОННО: на главной пункты подвала ведут на
    # якоря внутри страницы (#sale), на buy пункт «Покупка» ведёт на саму себя,
    # а страницы в подпапках ссылаются через ../. Сторожу важен состав и вид
    # подвала, а не куда ведёт каждая ссылка, — иначе он кричит на задуманное.
    т = re.sub(r'(href|src)="[^"]*"', r'\1="…"', кусок_текста)
    return re.sub(r'\s+', ' ', т).strip()


def кусок(текст, имя):
    н = текст.find('<!-- PLP:%s:START -->' % имя)
    к = текст.find('<!-- PLP:%s:END -->' % имя)
    if н < 0 or к < н:
        return None
    return текст[н:к].strip()


def страницы():
    из = []
    for корень, папки, файлы in os.walk(КОРЕНЬ):
        папки[:] = [п for п in папки if п not in {'.git', 'node_modules', 'build', 'tools'}
                    and not п.startswith('.')]
        for имя in файлы:
            if имя.endswith('.html'):
                из.append(os.path.join(корень, имя))
    return sorted(из)


def короткое(путь):
    return os.path.relpath(путь, КОРЕНЬ)


def главное():
    беды = []
    эталон_ui = open(os.path.join(КОРЕНЬ, 'build/parts/ui-common.css'),
                     encoding='utf-8').read().strip()

    подвалы = {}
    шапки = {'site': {}, 'cabinet': {}}
    проверено = 0

    for путь in страницы():
        текст = open(путь, encoding='utf-8', errors='ignore').read()
        ui = кусок(текст, 'UI')
        if ui is not None:
            проверено += 1
            # внутри маркера лежит <style>…</style> — сравниваем содержимое
            тело = re.sub(r'^.*?<style[^>]*>|</style>.*?$', '', ui, flags=re.S).strip()
            if тело != эталон_ui:
                беды.append(('PLP:UI разошёлся с build/parts/ui-common.css', короткое(путь)))
        ф = кусок(текст, 'FOOTER')
        if ф is not None:
            проверено += 1
            подвалы.setdefault(ровно(ф), []).append(короткое(путь))
        ш = кусок(текст, 'HEADER')
        if ш is not None:
            вид = 'cabinet' if 'owner.html' in путь else 'site'
            шапки[вид].setdefault(ровно(ш), []).append(короткое(путь))

    if len(подвалы) > 1:
        группы = sorted(подвалы.values(), key=len, reverse=True)
        большая = set(группы[0])
        for гр in группы[1:]:
            for стр in гр:
                беды.append(('подвал отличается от остальных %d страниц' % len(большая), стр))

    for вид, карта in шапки.items():
        if len(карта) > 1:
            группы = sorted(карта.values(), key=len, reverse=True)
            for гр in группы[1:]:
                for стр in гр:
                    беды.append(('шапка отличается от остальных страниц вида «%s»' % вид, стр))

    if беды:
        print('[единый вид] 🔴 общие части разъехались:')
        for что, где in беды:
            print('   %-46s %s' % (что, где))
        print('[единый вид] расхождений %d' % len(беды))
        return 1
    if not ТИХО:
        print('[единый вид] ок: общие части совпадают, сверок %d' % проверено)
    return 0


if __name__ == '__main__':
    sys.exit(главное())
