#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Порядок блоков главной страницы: по логике разговора, а не как сложилось.

Эльнур 20.09.2026: «блоки сайта организованы немного странно, главная страница
что бы ты там оставил по логике, о нас, что бы ты там оставил по логике, вообще
профи проанализируй и дай мне предложение сильное… чтобы не было перегруза, было
всё эффективно и логично».

КАК БЫЛО (14 блоков, 8 300 px):

    hero · ПРОДАЖА · консультант · АРЕНДА · почему Пхукет · PDF · сделки ·
    карта · квиз · наш подход · Эльнур · услуги · FAQ · список объектов

Три вещи ломали логику:

  1. Блок «Спросите Дарью» врезан МЕЖДУ продажей и арендой. Человек листает
     каталог — его посреди каталога прерывают. При этом кнопка «Дарья · на связи»
     и так висит на экране всё время: блок повторяет то, что уже есть.
  2. Про то, что мы делаем, рассказано ДВАЖДЫ и в разных местах: «наш подход»
     (9-й блок) и «услуги под ключ» (12-й). Между ними — рассказ об основателе.
  3. Знакомство («Здравствуйте, меня зовут Эльнур») стоит одиннадцатым. Человек
     десять блоков читает советы от неизвестно кого. При нашей подаче — тихий
     консалтинг, не витрина — это самая дорогая ошибка порядка.

КАК СТАЛО — порядок повторяет живой разговор:

    hero          обещание и два действия
    ПРОДАЖА  ─┐
    АРЕНДА   ─┘  каталог одним куском, без врезок
    квиз          «не нашли своё? — восемь вопросов, пришлём подборку»
    карта         «не знаете район? — вот чем они отличаются»
    Эльнур        «а кто это всё говорит» — знакомство ровно там, где возникает
    сделки        доказательство сразу после знакомства
    почему Пхукет рынок и доходность — когда уже интересно
    наш подход ─┐
    услуги     ─┘ что берём на себя — два блока рядом, а не через страницу
    PDF           забрать с собой
    консультант   «остались вопросы — спросите Дарью»
    FAQ           частые вопросы
    объекты       список ссылками: он нужен поиску, чтобы страницы объектов не
                  остались без внутренних ссылок (см. gen.mjs про 28 сирот)

Ничего не удалено — только переставлено, и трём блокам без имени выданы имена
(pdf, deals, services), чтобы сборка выбирала их по имени, а не по номеру.

    python3 site_blocks_order.py            # показать новый порядок
    python3 site_blocks_order.py --apply    # переставить
"""
import re, sys

APPLY = '--apply' in sys.argv
FILE = '/Users/elnurkhankishiev/plp-site/index.html'

# имена для блоков, которые их не имели
ИМЕНА = {'PDF · 23 страницы': 'pdf', 'Сделки': 'deals', 'Организуем всё': 'services'}

# порядок по именам блоков
ПОРЯДОК = ['hero', 'sale', 'rent', 'quiz', 'map', 'about', 'deals', 'why',
           'do', 'services', 'pdf', 'assistant', 'faq', 'all-objects']


def разбор(body):
    """Список блоков: (имя, html).

    Границу блока ведём не по самому <section>, а по комментариям-маркерам перед
    ним. 21.09: маркер `PLP:PART:cases:START` стоял строкой выше своей секции и
    при перестановке остался в чужом блоке — его пара разъехалась (START ушёл
    ниже END), и сборка страницы «О нас» упала. Маркер принадлежит той секции,
    которую открывает, и ездит вместе с ней.
    """
    старты = []
    for m in re.finditer(r'<section\b[^>]*>', body):
        i = m.start()
        пред = re.search(r'(?:\s*<!--[^>]*-->)+\s*$', body[:i])
        старты.append((пред.start() if пред else i, m.group(0)))
    блоки = []
    for k, (i, тег) in enumerate(старты):
        j = старты[k + 1][0] if k + 1 < len(старты) else len(body)
        кусок = body[i:j]
        m = re.search(r'id="([^"]+)"', тег)
        имя = m.group(1) if m else None
        if not имя:
            kk = re.search(r'class="kicker"[^>]*>(.*?)<', кусок, re.S)
            подпись = re.sub(r'<[^>]+>', '', kk.group(1)).strip() if kk else ''
            имя = ИМЕНА.get(подпись)
            if имя:
                # даём блоку имя прямо в разметке: сборка выбирает секции по нему
                кусок = кусок.replace(тег, тег[:-1] + ' id="%s">' % имя, 1)
            elif k == 0:
                имя = 'hero'
                кусок = кусок.replace(тег, тег[:-1] + ' id="hero">', 1)
        блоки.append((имя, кусок))
    return блоки


def main():
    s = open(FILE, encoding='utf-8').read()
    m0 = s.index('<main'); mo = s.index('>', m0) + 1; me = s.index('</main>')
    блоки = разбор(s[mo:me])
    было = [имя for имя, _ in блоки]
    карта = dict(блоки)

    пропало = [x for x in было if x not in ПОРЯДОК]
    лишнее = [x for x in ПОРЯДОК if x not in карта]
    if пропало or лишнее:
        print('РАСХОЖДЕНИЕ — не переставляю.')
        if пропало: print('  блок есть на странице, но не в порядке:', пропало)
        if лишнее: print('  блок в порядке, но его нет на странице:', лишнее)
        return 1

    print('было:  ' + ' · '.join(было))
    print('стало: ' + ' · '.join(ПОРЯДОК))
    сдвиг = sum(1 for i, x in enumerate(ПОРЯДОК) if было[i] != x)
    print('\nблоков переставлено: %d из %d' % (сдвиг, len(ПОРЯДОК)))
    if not APPLY:
        print('\nЭто отчёт. Переставить: --apply')
        return 0
    новый = '\n'.join(карта[x].rstrip() for x in ПОРЯДОК)
    # пары маркеров PLP:PART обязаны остаться в правильном порядке: по ним
    # собираются страница «О нас» и страница управления
    for имя in set(re.findall(r'PLP:PART:([a-z-]+):START', новый)):
        a = новый.find('<!-- PLP:PART:%s:START -->' % имя)
        b = новый.find('<!-- PLP:PART:%s:END -->' % имя)
        if a < 0 or b < 0 or b < a:
            print('ОСТАНОВКА: кусок «%s» разъехался бы (START %d, END %d)' % (имя, a, b))
            return 1
    open(FILE, 'w', encoding='utf-8').write(s[:mo] + '\n' + новый + '\n' + s[me:])
    print('\nindex.html: порядок блоков обновлён')
    print('дальше: node build/mkpages.mjs && node build/mkassets.mjs')
    return 0


if __name__ == '__main__':
    sys.exit(main())
